#!/bin/sh
# Публикация архива в GitHub одной командой, без слияний и без потери истории.
#
#   sh tools/push-from-archive.sh ~/storage/downloads/baby-tracker.tar "текст коммита"
#
# ЗАЧЕМ ТАК. Конфликты слияния возникали не из-за git, а из-за того, что
# правки приходили из трёх мест: веб-редактор GitHub, VPS и присланный
# архив. Git видел разошедшиеся истории и просил выбрать, чья версия
# файла верна, — а выбирать было нечего, потому что архив это ПОЛНАЯ
# замена дерева, а не набор изменений.
#
# Здесь слияния не происходит вовсе. Порядок такой:
#   1. локальная копия приводится к ТОЧНОМУ состоянию GitHub;
#   2. поверх раскладывается архив;
#   3. разница уходит одним обычным коммитом.
# Раз локальная ветка не расходилась с удалённой, push всегда
# fast-forward, и мержить нечего по определению.
#
# `git reset --hard` трогает ТОЛЬКО копию на телефоне. История в GitHub
# не меняется, ветки не переписываются, `--force` здесь не нужен нигде.
#
# ВАЖНОЕ СЛЕДСТВИЕ: архив считается источником истины. Если между
# присылками архива что-то правилось прямо на сайте GitHub, эта правка
# в файлах пропадёт (в истории останется и восстановима, но в рабочем
# дереве её не будет). Поэтому либо правьте только через архив, либо
# говорите, что поменяли на сайте, чтобы это вошло в следующий архив.

set -e

ARCHIVE="$1"
MESSAGE="${2:-Обновление из архива}"

if [ -z "$ARCHIVE" ] || [ ! -f "$ARCHIVE" ]; then
  echo "Не найден архив: $ARCHIVE" >&2
  echo "Использование: sh tools/push-from-archive.sh <путь-к-tar> [сообщение]" >&2
  exit 1
fi

# Работаем из корня репозитория, откуда бы скрипт ни запустили
cd "$(git rev-parse --show-toplevel)"

BRANCH="$(git rev-parse --abbrev-ref HEAD)"
echo "Ветка: $BRANCH"

echo "1/4 Забираю текущее состояние GitHub…"
git fetch origin
git reset --hard "origin/$BRANCH"

# Удаляем ОТСЛЕЖИВАЕМЫЕ файлы перед распаковкой. Без этого файлы,
# удалённые в новой версии, остались бы на диске: tar кладёт поверх, но
# ничего не удаляет, и `git add -A` не увидел бы удаления. Неотслеживаемое
# (data/, node_modules, ключи) не трогаем — оно git и не принадлежит.
echo "2/4 Расчищаю отслеживаемые файлы…"
git ls-files -z | xargs -0 rm -f

echo "3/4 Распаковываю архив…"
tar -xf "$ARCHIVE" --strip-components=1 -C .

if git diff --quiet && git diff --cached --quiet && [ -z "$(git status --porcelain)" ]; then
  echo "Изменений нет — коммитить нечего."
  exit 0
fi

echo "4/4 Коммит и отправка…"
git add -A
git commit -m "$MESSAGE"
git push origin "$BRANCH"

echo
echo "Готово. Отправлено в origin/$BRANCH:"
git --no-pager log --oneline -1
