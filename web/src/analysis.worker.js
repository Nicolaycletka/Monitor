/*
 * Фоновый поток для тяжёлых расчётов прогноза.
 *
 * predictNext, selfCheck и sourceScores — проверки задним числом: на
 * каждый недавний сон строится прогноз «как будто его ещё не было».
 * Даже после ускорения это сотни миллисекунд на ноутбуке и секунды на
 * телефоне, и пока они шли в основном потоке, экран не отвечал ни на
 * что: вкладки не переключались, «Заснул» не нажималось.
 *
 * Здесь они считаются в отдельном потоке, интерфейс их не ждёт. Кеши
 * sleep.js живут в этом потоке и переживают запросы — повторный расчёт
 * по тем же снам почти бесплатный.
 *
 * Протокол: { id, kind, p } → { id, ok, r } или { id, ok: false, err }.
 * Список видов расчёта — в analysis-run.js (RUN), один на оба потока.
 */
import { RUN } from "./analysis-run.js";

self.onmessage = (e) => {
  const { id, kind, p } = e.data || {};
  try {
    const fn = RUN[kind];
    if (!fn) throw new Error(`неизвестный расчёт: ${kind}`);
    self.postMessage({ id, ok: true, r: fn(p) });
  } catch (err) {
    self.postMessage({ id, ok: false, err: String(err?.message || err) });
  }
};
