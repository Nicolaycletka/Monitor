/** Возраст в неделях/месяцах от точки отсчёта, дни -> нужная единица. */
const toWeeks = (days) => days / 7;
const toMonths = (days) => days / DAYS_PER_MONTH;

/**
 * Все триггеры одним списком: [момент (мс с эпохи), текст, ключ].
 * `anchor` — точка отсчёта для скачков: ПДР, если задана, иначе
 * дата рождения. Для месячных вех точка отсчёта всегда рождение,
 * это в самом источнике данных ("по фактической дате рождения").
 */
function buildSchedule(birth, dueAt) {
  const leapAnchor = Number.isFinite(dueAt) ? dueAt : birth;
  const items = [
    ...MONTHS.map((x) => ({
      at: birth + x.m * DAYS_PER_MONTH * DAY,
      text: x.text,
      lead: x.lead,
      key: `m${x.m}`,
    })),
    ...LEAPS.map((x) => ({
      at: leapAnchor + x.week * WEEK,
      text: x.text,
      lead: x.lead,
      key: `l${x.week}`,
    })),
  ];
  return items.sort((a, b) => a.at - b.at);
}

/**
 * Ближайшее уведомление о развитии — либо ещё не наступившее, либо
 * упущенное не дальше `CATCH_UP_MS` назад. Возвращает null, если
 * нечего показать (список исчерпан или дата рождения не задана).
 */
export function nextMilestone(birth, dueAt, now = Date.now()) {
  if (!Number.isFinite(birth)) return null;
  const items = buildSchedule(birth, dueAt);
  const next = items.find((x) => x.at > now - CATCH_UP_MS);
  if (!next) return null;
  return { at: next.at, text: next.text, lead: next.lead, key: next.key };
}

/** Для показа в интерфейсе: сколько вех уже позади и что ближайшее. */
export function milestoneOverview(birth, dueAt, now = Date.now()) {
  if (!Number.isFinite(birth)) return null;
  const items = buildSchedule(birth, dueAt);
  const passed = items.filter((x) => x.at <= now).length;
  const next = items.find((x) => x.at > now);
  return {
    total: items.length,
    passed,
    next: next ? { at: next.at, text: next.text, lead: next.lead } : null,
    usingDueDate: Number.isFinite(dueAt),
  };
}
