/** Средняя длина месяца в днях — ВОЗ считает возраст в месяцах так же. */
export const DAYS_PER_MONTH = 30.4375;

/** Узлы в общем виде: [день, L, M, S], отсортированы по дню. */
const build = (weeks, months) => [
  ...weeks.map((v, i) => [i * 7, ...v]),
  ...months.map((v, i) => [(i + 4) * DAYS_PER_MONTH, ...v]),
];

const TABLE = { m: build(WEEKS_M, MONTHS_M), f: build(WEEKS_F, MONTHS_F) };

export const SEX_LABEL = { m: "Мальчик", f: "Девочка" };
/** Родительный падеж — для фраз вида «кривые для девочки». */
export const SEX_GEN = { m: "мальчика", f: "девочки" };
export const MAX_DAYS = 60 * DAYS_PER_MONTH;

/**
 * L, M, S на произвольный возраст в днях. За краями таблицы —
 * ближайший узел; вызывающий код должен сам решить, показывать ли
 * такую оценку (см. inRange).
 */
export function lms(sex, days) {
  const t = TABLE[sex];
  if (!t) return null;
  const d = Math.min(Math.max(days, 0), MAX_DAYS);
  let i = 1;
  while (i < t.length - 1 && t[i][0] < d) i += 1;
  const [d0, l0, m0, s0] = t[i - 1];
  const [d1, l1, m1, s1] = t[i];
  const k = d1 === d0 ? 0 : (d - d0) / (d1 - d0);
  return {
    L: l0 + k * (l1 - l0),
    M: m0 + k * (m1 - m0),
    S: s0 + k * (s1 - s0),
  };
}

export const inRange = (days) => days >= 0 && days <= MAX_DAYS;

/** z-оценка веса (кг) для возраста в днях. */
export function zOf(sex, days, kg) {
  const p = lms(sex, days);
  if (!p || !(kg > 0)) return null;
  const { L, M, S } = p;
  return Math.abs(L) < 1e-7
    ? Math.log(kg / M) / S
    : (Math.pow(kg / M, L) - 1) / (L * S);
}

/** Вес (кг), соответствующий z-оценке в этом возрасте. */
export function kgAt(sex, days, z) {
  const p = lms(sex, days);
  if (!p) return null;
  const { L, M, S } = p;
  if (Math.abs(L) < 1e-7) return M * Math.exp(S * z);
  const base = 1 + L * S * z;
  if (base <= 0) return null; // распределение обрывается, z за краем
  return M * Math.pow(base, 1 / L);
}

/** Медиана веса в этом возрасте, кг. */
export const medianKg = (sex, days) => lms(sex, days)?.M ?? null;

/** Прирост медианы ВОЗ между двумя возрастами, кг. Грубый ориентир. */
export function medianGain(sex, fromDays, toDays) {
  const a = medianKg(sex, fromDays);
  const b = medianKg(sex, toDays);
  return a == null || b == null ? null : b - a;
}

/* ---------- нормальное распределение ---------- */

/**
 * Функция ошибок, приближение Abramowitz & Stegun 7.1.26.
 * Точность ~1.5e-7 по абсолютной величине — с запасом для процентов.
 */
function erf(x) {
  const s = x < 0 ? -1 : 1;
  const a = Math.abs(x);
  const t = 1 / (1 + 0.3275911 * a);
  const y =
    1 -
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t +
      0.254829592) *
      t *
      Math.exp(-a * a);
  return s * y;
}

/** Перцентиль (0…100) по z-оценке. */
export const pctOf = (z) => 50 * (1 + erf(z / Math.SQRT2));

/**
 * Перцентиль для показа человеку. У краёв «0» и «100» выглядят как
 * ошибка, поэтому зажимаем и отмечаем знаком.
 */
export function pctText(z) {
  const p = pctOf(z);
  if (p < 0.5) return "<1";
  if (p > 99.5) return ">99";
  return String(Math.round(p));
}

/* ---------- работа с записями ---------- */

/**
 * Записи веса, отсортированные по времени. Вес хранится в ГРАММАХ
 * целым числом: дробные килограммы в JSON и в арифметике дают
 * 6.300000000000001, а вес — величина, которую пользователь вводит
 * с точностью до 10 г.
 */
export function weightPoints(events, birth) {
  return events
    .filter((e) => e.type === "weight" && !e.deleted && Number.isFinite(e.meta?.g))
    .map((e) => ({
      id: e.id,
      ts: e.start,
      g: e.meta.g,
      kg: e.meta.g / 1000,
      days: (e.start - birth) / 86400000,
    }))
    .filter((p) => p.days >= -1)
    .sort((a, b) => a.ts - b.ts);
}

/** z-оценки для тех точек, что попали в диапазон таблицы. */
export function withZ(points, sex) {
  return points.map((p) => ({
    ...p,
    z: sex && inRange(p.days) ? zOf(sex, p.days, p.kg) : null,
  }));
}

/** Минимальный интервал между взвешиваниями, по которому считаем темп. */
export const GAIN_MIN_DAYS = 7;

/**
 * Темп прибавки: берём последнее взвешивание и самое свежее из тех,
 * что отстоят от него хотя бы на GAIN_MIN_DAYS. Пара соседних
 * взвешиваний через день бесполезна: домашние весы врут на ±20–50 г,
 * и на коротком плече эта ошибка становится больше самой прибавки.
 */
export function gainRate(points, sex) {
  if (points.length < 2) return null;
  const last = points[points.length - 1];
  let prev = null;
  for (let i = points.length - 2; i >= 0; i -= 1) {
    if (last.days - points[i].days >= GAIN_MIN_DAYS) { prev = points[i]; break; }
  }
  if (!prev) return null;
  const days = last.days - prev.days;
  const gramsPerDay = (last.g - prev.g) / days;
  const ref = sex ? medianGain(sex, prev.days, last.days) : null;
  return {
    from: prev,
    to: last,
    days,
    grams: last.g - prev.g,
    gramsPerDay,
    refGramsPerDay: ref == null ? null : (ref * 1000) / days,
  };
}

/** Насколько z ушёл от максимума за историю — и за какой срок. */
export const Z_DROP_ALARM = 1.0;

/**
 * Сдвиг по коридору. Смотрим на разницу между наибольшим z в истории
 * и текущим. Порог в 1.0 z взят из консенсусных определений faltering
 * growth (NICE NG75 оперирует «полосами» британских кривых, они шире
 * на 2/3 z; более поздний консенсус формулирует то же через падение
 * z-оценки на 1.0).
 *
 * Первые три недели исключены намеренно: физиологическая убыль веса
 * (до 7–10 % от веса при рождении, восстановление к 10–14 дню) — это
 * норма, а по z-оценке она выглядит как обвал на целую единицу.
 */
export function zTrend(points, sex) {
  if (!sex) return null;
  const usable = points
    .map((p) => ({ ...p, z: inRange(p.days) ? zOf(sex, p.days, p.kg) : null }))
    .filter((p) => p.z != null && p.days >= 21);
  if (usable.length < 2) return null;
  const last = usable[usable.length - 1];
  let peak = usable[0];
  for (const p of usable) if (p.z > peak.z) peak = p;
  if (peak.ts >= last.ts) return { drop: 0, last, peak: last, span: 0 };
  return {
    drop: peak.z - last.z,
    last,
    peak,
    span: last.days - peak.days,
  };
}

/**
 * Разбор того, что человек ввёл в поле веса. Принимаем килограммы
 * («6.35», «6,35») и граммы («6350»): на телефоне точка и запятая
 * попадаются обе, а привычка вводить граммы есть у половины людей.
 * Возвращает граммы или null.
 */
export function parseWeight(raw) {
  const s = String(raw).trim().replace(",", ".").replace(/\s/g, "");
  if (!s || !/^\d+(\.\d+)?$/.test(s)) return null;
  const n = Number(s);
  if (!Number.isFinite(n)) return null;
  const g = n >= 100 ? Math.round(n) : Math.round(n * 1000);
  return g >= 500 && g <= 40000 ? g : null;
}

