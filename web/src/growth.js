/**
 * Антропометрия по стандартам ВОЗ (WHO Child Growth Standards, 2006):
 * вес-к-возрасту, длина-к-возрасту и окружность головы-к-возрасту.
 *
 * Таблицы L/M/S взяты из официальных публикаций ВОЗ (z-scores):
 * понедельные «Birth to 13 weeks» и помесячные («Birth to 5 years»
 * для веса и головы, «Birth to 2 years» для длины). Первые 13 недель
 * берутся из недельной таблицы, дальше — из месячной с 4-го месяца.
 * Стык проверен: неделя 13 (день 91) и месяц 3 (день 91.3) в таблицах
 * ВОЗ дают практически одинаковые L/M/S.
 *
 * L, M, S — параметры распределения Бокса-Кокса: M это медиана,
 * S — обобщённый коэффициент вариации, L — степень преобразования.
 * Отсюда ровно две формулы, всё остальное в файле — обвязка:
 *
 *   z = ((значение / M)^L − 1) / (L·S)       при L ≠ 0
 *   значение = M·(1 + L·S·z)^(1/L)           при L ≠ 0
 *
 * У длины и окружности головы ВОЗ полагает L = 1 на всех возрастах —
 * распределение нормальное, и формула вырождается в M + z·M·S. Код
 * этого не знает и считает общим случаем: так одна ветка вместо двух,
 * а результат тот же.
 *
 * Между узлами L, M и S интерполируются линейно по дням — это то,
 * что рекомендует делать CDC для промежуточных возрастов.
 *
 * Чего здесь НЕТ и о чём надо помнить:
 *   - Стандарт построен на доношенных детях. Для недоношенного нужен
 *     скорректированный возраст, приложение его не считает.
 *   - За пределами ±3 z ВОЗ для отчётности использует не эту формулу,
 *     а линейную экстраполяцию по расстоянию между 2 и 3 SD. Здесь
 *     считается по формуле — на краях это приблизительно.
 *   - Длина в таблицах ВОЗ — это длина ЛЁЖА (recumbent length).
 *     После двух лет ВОЗ измеряет рост стоя, это другая величина
 *     (примерно на 0.7 см меньше), поэтому таблица длины здесь
 *     обрывается на 24 месяцах, а не тянется до пяти лет.
 */

