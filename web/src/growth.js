/** Записи показателя, отсортированные по времени. */
export function measurements(ind, events, birth) {
  return events
    .filter((e) => e.type === ind.key && !e.deleted && Number.isFinite(e.meta?.[ind.metaKey]))
    .map((e) => ({
      id: e.id,
      ts: e.start,
      raw: e.meta[ind.metaKey],
      value: e.meta[ind.metaKey] / ind.perUnit,
      days: (e.start - birth) / 86400000,
    }))
    .filter((p) => p.days >= -1)
    .sort((a, b) => a.ts - b.ts);
}

/** Минимальный интервал между измерениями, по которому считаем темп. */
export const GAIN_MIN_DAYS = 7;

/**
 * Темп прироста: последнее измерение и самое свежее из тех, что
 * отстоят от него хотя бы на GAIN_MIN_DAYS. Пара соседних измерений
 * через день бесполезна: погрешность домашних весов и особенно
 * сантиметровой ленты на коротком плече больше самого прироста.
 */
export function gainRate(ind, points, sex) {
  if (points.length < 2) return null;
  const last = points[points.length - 1];
  let prev = null;
  for (let i = points.length - 2; i >= 0; i -= 1) {
    if (last.days - points[i].days >= GAIN_MIN_DAYS) { prev = points[i]; break; }
  }
  if (!prev) return null;
  const days = last.days - prev.days;
  const ref = sex ? medianGain(ind, sex, prev.days, last.days) : null;
  return {
    from: prev,
    to: last,
    days,
    delta: last.raw - prev.raw,
    perWeek: ((last.raw - prev.raw) / days) * 7,
    refPerWeek: ref == null ? null : ((ref * ind.perUnit) / days) * 7,
  };
}

/** Порог смещения по коридору, при котором стоит показать педиатру. */
export const Z_DROP_ALARM = 1.0;

/**
 * Сдвиг по коридору: разница между экстремумом z за историю и текущим
 * значением. Порог в 1.0 z взят из консенсусных определений faltering
 * growth (NICE NG75 оперирует «полосами» британских кривых, они шире
 * на 2/3 z; более поздний консенсус формулирует то же через падение
 * z-оценки на 1.0).
 *
 * Первые три недели исключены намеренно: физиологическая убыль веса
 * (до 7–10 % от веса при рождении, восстановление к 10–14 дню) — это
 * норма, а по z-оценке она выглядит как обвал на целую единицу.
 * Для длины и головы это правило безвредно, поэтому общее.
 */
export function zTrend(ind, points, sex) {
  if (!sex) return null;
  const usable = points
    .map((p) => ({ ...p, z: inRange(ind, p.days) ? zOf(ind, sex, p.days, p.value) : null }))
    .filter((p) => p.z != null && p.days >= 21);
  if (usable.length < 2) return null;
  const last = usable[usable.length - 1];

  let down = usable[0];
  let up = usable[0];
  for (const p of usable) {
    if (p.z > down.z) down = p;
    if (p.z < up.z) up = p;
  }
  // берём то направление, в котором смещение больше и раньше по времени
  const cand = [];
  if (down.ts < last.ts) cand.push({ from: down, shift: down.z - last.z, dir: "down" });
  if (ind.alarm === "both" && up.ts < last.ts) {
    cand.push({ from: up, shift: last.z - up.z, dir: "up" });
  }
  if (!cand.length) return { shift: 0, last, from: last, span: 0, dir: null };
  cand.sort((a, b) => b.shift - a.shift);
  const best = cand[0];
  return { shift: best.shift, dir: best.dir, from: best.from, last, span: last.days - best.from.days };
}

/**
 * Разбор того, что человек ввёл. Принимаем и отображаемые единицы
 * («6,35» кг, «61,4» см), и внутренние («6350» г, «614» мм): на
 * телефоне точка и запятая попадаются обе, а привычка вводить граммы
 * и миллиметры есть у половины людей. Возвращает внутренние единицы
 * или null.
 */
export function parseValue(ind, raw) {
  const s = String(raw).trim().replace(",", ".").replace(/\s/g, "");
  if (!s || !/^\d+(\.\d+)?$/.test(s)) return null;
  const n = Number(s);
  if (!Number.isFinite(n)) return null;
  const v = n >= ind.rawIfAbove ? Math.round(n) : Math.round(n * ind.perUnit);
  return v >= ind.min && v <= ind.max ? v : null;
}

/** «6,35» / «61,4» — значение для показа, без хвостовых нулей. */
export function valueText(ind, v) {
  return (v / ind.perUnit)
    .toFixed(ind.decimals)
    .replace(/(\.\d*?)0+$/, "$1")
    .replace(/\.$/, "")
    .replace(".", ",");
}
