/**
 * Вес-к-возрасту по стандартам ВОЗ (WHO Child Growth Standards, 2006).
 *
 * Что здесь лежит и откуда:
 *
 * Таблицы LMS взяты из официальных публикаций ВОЗ, weight-for-age,
 * z-scores:
 *   - «Birth to 13 weeks» — узлы по неделям (wfa-boys/girls-0-13-zscores);
 *   - «Birth to 5 years»  — узлы по месяцам (wfa-boys/girls-0-5-zscores).
 * Первые 13 недель взяты из недельной таблицы, дальше — из месячной,
 * начиная с 4-го месяца. Стык проверен: неделя 13 (день 91) и месяц 3
 * (день 91.3) в таблицах ВОЗ дают практически одинаковые L/M/S
 * (мальчики 6.3690 против 6.3762 кг медианы), так что разрыва нет.
 *
 * L, M, S — параметры распределения Бокса-Кокса: M это медиана,
 * S — обобщённый коэффициент вариации, L — степень преобразования.
 * Отсюда ровно две формулы, всё остальное в файле — обвязка:
 *
 *   z = ((вес / M)^L − 1) / (L·S)          при L ≠ 0
 *   вес = M·(1 + L·S·z)^(1/L)              при L ≠ 0
 *
 * (при L = 0 — логарифмический вариант, у веса-к-возрасту L обращается
 * в ноль примерно на 4-м месяце у девочек, так что ветка живая.)
 *
 * Между узлами L, M и S интерполируются линейно по дням. Это то, что
 * рекомендует делать сам CDC для промежуточных возрастов; ошибка на
 * стыке недельной и месячной частей — порядка 20 г, то есть 0.03 z.
 *
 * Чего здесь НЕТ и о чём надо помнить:
 *   - Стандарт построен на доношенных детях. Для недоношенного нужен
 *     скорректированный возраст, приложение его не считает.
 *   - За пределами ±3 z ВОЗ для отчётности использует не эту формулу,
 *     а линейную экстраполяцию по расстоянию между 2 и 3 SD. Здесь
 *     считается по формуле — на краях это приблизительно, и показывать
 *     такие числа как точные нельзя.
 *   - Отдельный стандарт ВОЗ на СКОРОСТЬ прибавки (weight velocity)
 *     существует и считается иначе. Разность медиан, которую даёт
 *     medianGain(), — это не он, а грубый ориентир.
 */

