export const maxDays = (ind) => ind.maxMonths * DAYS_PER_MONTH;
export const inRange = (ind, days) => days >= 0 && days <= maxDays(ind);

/**
 * L, M, S на произвольный возраст в днях. За краями таблицы —
 * ближайший узел; вызывающий код сам решает, показывать ли такую
 * оценку (см. inRange).
 */
export function lms(ind, sex, days) {
  const t = ind.table[sex];
  if (!t) return null;
  const d = Math.min(Math.max(days, 0), maxDays(ind));
  let i = 1;
  while (i < t.length - 1 && t[i][0] < d) i += 1;
  const [d0, l0, m0, s0] = t[i - 1];
  const [d1, l1, m1, s1] = t[i];
  const k = d1 === d0 ? 0 : (d - d0) / (d1 - d0);
  return { L: l0 + k * (l1 - l0), M: m0 + k * (m1 - m0), S: s0 + k * (s1 - s0) };
}

/** z-оценка значения (в ОТОБРАЖАЕМЫХ единицах: кг или см). */
export function zOf(ind, sex, days, value) {
  const p = lms(ind, sex, days);
  if (!p || !(value > 0)) return null;
  const { L, M, S } = p;
  return Math.abs(L) < 1e-7
    ? Math.log(value / M) / S
    : (Math.pow(value / M, L) - 1) / (L * S);
}

/** Значение, соответствующее z-оценке в этом возрасте. */
export function valueAt(ind, sex, days, z) {
  const p = lms(ind, sex, days);
  if (!p) return null;
  const { L, M, S } = p;
  if (Math.abs(L) < 1e-7) return M * Math.exp(S * z);
  const base = 1 + L * S * z;
  if (base <= 0) return null; // распределение обрывается, z за краем
  return M * Math.pow(base, 1 / L);
}

/** Медиана в этом возрасте. */
export const medianOf = (ind, sex, days) => lms(ind, sex, days)?.M ?? null;

/** Прирост медианы ВОЗ между двумя возрастами. Грубый ориентир. */
export function medianGain(ind, sex, fromDays, toDays) {
  const a = medianOf(ind, sex, fromDays);
  const b = medianOf(ind, sex, toDays);
  return a == null || b == null ? null : b - a;
}

/** Медиана веса, кг — короткий доступ для модели кормлений. */
export const medianKg = (sex, days) => medianOf(IND.weight, sex, days);

/* ---------- нормальное распределение ---------- */

/**
 * Функция ошибок, приближение Abramowitz & Stegun 7.1.26.
 * Точность ~1.5e-7 по абсолютной величине — с запасом для процентов.
 */
function erf(x) {
  const s = x < 0 ? -1 : 1;
  const a = Math.abs(x);
  const t = 1 / (1 + 0.3275911 * a);
  const y =
    1 -
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t +
      0.254829592) * t * Math.exp(-a * a);
  return s * y;
}

/** Перцентиль (0…100) по z-оценке. */
export const pctOf = (z) => 50 * (1 + erf(z / Math.SQRT2));

/** Перцентиль для показа человеку: у краёв «0» и «100» пугают зря. */
export function pctText(z) {
  const p = pctOf(z);
  if (p < 0.5) return "<1";
  if (p > 99.5) return ">99";
  return String(Math.round(p));
}

