/** Средняя длина месяца в днях — ВОЗ считает возраст в месяцах так же. */
export const DAYS_PER_MONTH = 30.4375;

/** Узлы в общем виде: [день, L, M, S]. */
const buildLMS = (weeks, months) => [
  ...weeks.map((v, i) => [i * 7, ...v]),
  ...months.map((v, i) => [(i + 4) * DAYS_PER_MONTH, ...v]),
];
/** То же для показателей с L = 1: узлы заданы парами [M, S]. */
const buildL1 = (weeks, months) => [
  ...weeks.map(([m, s], i) => [i * 7, 1, m, s]),
  ...months.map(([m, s], i) => [(i + 4) * DAYS_PER_MONTH, 1, m, s]),
];

