/**
 * Самообновление приложения при расхождении сборок.
 *
 * Зачем. Тексты вех развития (и вообще всё содержимое пушей) живут в
 * бандле НА ТЕЛЕФОНЕ и уезжают на сервер уже готовой строкой. Значит
 * залипший клиент молча шлёт устаревшее, а снаружи это выглядит как
 * «пуш пришёл не тот». Так и случилось: сервер и сборка на VPS были
 * новые, а телефон третий день слал текст прошлой версии.
 *
 * Service worker эту дыру не закрывает. Файл `sw.js` между деплоями не
 * меняется — браузеру нечего заметить и нечего обновлять. Меняется имя
 * собранного бандла, но PWA, которую не закрывали, при возврате из
 * фона навигацию не делает и новый index.html не запрашивает. То есть
 * приложение может крутиться на старом коде неограниченно долго, и
 * никакой сигнал до него не доходит.
 *
 * Как узнаём. `MY_BUILD` — имя файла, из которого загружен ЭТОТ модуль
 * (vite подставляет в него хеш содержимого). Сервер отдаёт в ответе на
 * синк имя файла, на который ссылается его index.html. Оба значения
 * выведены из одного артефакта, поэтому отдельную нумерацию версий
 * заводить не нужно и рассинхронизировать нечего.
 *
 * Когда перезагружаем. Не в момент обнаружения, а когда приложение в
 * следующий раз выведут на передний план: тогда пользователь ничего не
 * набирает и терять нечего, а обрывать заполнение формы ради обновления —
 * плохой размен. Один раз за сессию: sessionStorage страхует от петли,
 * если сравнение вдруг окажется ложным.
 */

const MY_BUILD = import.meta.url.split("/").pop() || "";

/** Версия из web/package.json, подставляется при сборке (vite.config.js). */
const MY_VERSION = typeof __APP_VERSION__ === "string" ? __APP_VERSION__ : null;
const FLAG = "bt-build-reloaded";

/*
 * Автономная сборка (файлы внутри APK) узнаётся по тому же признаку,
 * что и в store.js: заданному при сборке адресу API.
 *
 * Для неё перезагрузка БЕССМЫСЛЕННА и вредна. Файлы лежат в приложении,
 * перезагрузка поднимет ровно те же самые — и так на каждом выводе
 * приложения на передний план, вечно. Поэтому расхождение здесь не
 * перезагружает, а поднимает флаг: пользователю показывается, что вышла
 * новая версия и APK пора переустановить.
 *
 * Это единственный способ не вернуться к тому, из-за чего пуши о вехах
 * приходили со старым текстом. Устаревший клиент опасен именно тем, что
 * снаружи неотличим от исправного; здесь он хотя бы скажет о себе сам.
 */
const BUNDLED = Boolean(import.meta.env.VITE_API_URL);

let pending = null;
let updateAvailable = false;

/** Для автономной сборки: вышла ли на сервере версия новее этой. */
export const isUpdateAvailable = () => updateAvailable;

/** Вызывается из syncOnce с полем `build` из ответа сервера. */
export function noteServerBuild(build, version) {
  /*
   * Автономный APK сравнивает ВЕРСИЮ, а не имя файла.
   *
   * Его сборка идёт с другими BASE_PATH и VITE_API_URL, поэтому хеш
   * содержимого отличается от серверного всегда — даже когда обе
   * сборки сделаны из одного коммита. Сравнение хешей давало вечную
   * плашку «вышла новая версия» на самой свежей сборке, что и
   * случилось. Версия же одинакова, если коммит один.
   */
  if (BUNDLED) {
    if (!version || !MY_VERSION) return;   // нечего сравнивать
    updateAvailable = version !== MY_VERSION;
    return;
  }

  if (!build || !/\.js$/.test(MY_BUILD)) return; // дев-сервер: сравнивать нечего
  if (build === MY_BUILD) {
    updateAvailable = false;
    return;
  }
  try {
    if (sessionStorage.getItem(FLAG) === build) return; // уже перезагружались на эту
  } catch {
    return; // приватный режим без хранилища — лучше не трогать вовсе
  }
  pending = build;
}

/** Отдельно от noteServerBuild, чтобы это можно было проверить в тестах. */
export function shouldReloadNow(visibility) {
  return visibility === "visible" && Boolean(pending);
}

if (typeof document !== "undefined" && typeof location !== "undefined") {
  document.addEventListener("visibilitychange", () => {
    if (!shouldReloadNow(document.visibilityState)) return;
    try {
      sessionStorage.setItem(FLAG, pending);
    } catch {
      return;
    }
    location.reload();
  });
}
